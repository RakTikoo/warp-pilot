def _stack(out, shp, lead):
    arrs = []
    for o in out:
        a = _np.asarray(o, dtype=_np.float64)
        if a.shape != shp:
            a = _np.broadcast_to(a, shp)
        arrs.append(a)
    A = _np.stack(arrs).reshape(lead + shp)
    if not shp:
        return A
    return A.transpose(
        tuple(range(len(lead), len(lead) + len(shp)))
        + tuple(range(len(lead))))


