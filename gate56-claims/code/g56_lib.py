def _ss(u):
    """Quintic smootherstep and derivatives (clipped
    semantics identical to the registered _U/_H usage)."""
    u = np.asarray(u, dtype=DTYPE)
    uc = np.clip(u, 0.0, 1.0)
    s = 6.0 * uc ** 5 - 15.0 * uc ** 4 + 10.0 * uc ** 3
    sp = 30.0 * uc ** 4 - 60.0 * uc ** 3 + 30.0 * uc ** 2
    spp = 120.0 * uc ** 3 - 180.0 * uc ** 2 + 60.0 * uc
    inside = (u > 0.0) & (u < 1.0)
    return s, np.where(inside, sp, 0.0), np.where(inside, spp, 0.0)


def _U(r, a, b):
    """U(r; a, b) = SS((r - a)/(b - a)) on [a, b],
    0 below, 1 above (registered p316 form)."""
    r = np.asarray(r, dtype=DTYPE)
    s, sp, spp = _ss((r - a) / (b - a))
    return s, sp / (b - a), spp / (b - a) ** 2


def S_ab22(r):
    """S_{2,2} = 1 - I_u(3, 3), u = (r - 10)/10 on
    [10, 20]; 1 below, 0 above (registered p258 form)."""
    r = np.asarray(r, dtype=DTYPE)
    S = np.ones_like(r); Sp = np.zeros_like(r)
    Spp = np.zeros_like(r)
    S = np.where(r >= 20.0, 0.0, S)
    m = (r > 10.0) & (r < 20.0)
    if np.any(m):
        u = (r[m] - 10.0) / 10.0
        B = beta_fn(3.0, 3.0)
        S[m] = 1.0 - betainc(3.0, 3.0, u)
        Sp[m] = -(u ** 2 * (1.0 - u) ** 2) / (10.0 * B)
        fp = 2.0 * u * (1.0 - u) * (1.0 - 2.0 * u)
        Spp[m] = -fp / (100.0 * B)
    return S, Sp, Spp


def shape_B_plat(r, c=15.0, W=5.0, e=3.0):
    """Plateau bump B = H(x) H(y), x = (r - r1)/e,
    y = (r2 - r)/e (registered p274 form; H is the
    quintic _ss)."""
    r = np.asarray(r, dtype=DTYPE)
    r1, r2 = c - W, c + W
    Hx, Hpx, Hppx = _ss((r - r1) / e)
    Hy, Hpy, Hppy = _ss((r2 - r) / e)
    B = Hx * Hy
    Bp = (Hpx * Hy - Hx * Hpy) / e
    Bpp = (Hppx * Hy - 2.0 * Hpx * Hpy + Hx * Hppy) / e ** 2
    return B, Bp, Bpp


def lapse(r):
    B, Bp, Bpp = shape_B_plat(r)
    return (1.0 + LAPSE_A * B, LAPSE_A * Bp, LAPSE_A * Bpp)


