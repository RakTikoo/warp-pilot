def metric_g56(pts, pr, beta=BETA):
    """The metric from the ansatz (definition)."""
    pts = np.asarray(pts, dtype=DTYPE)
    S, _, _, N, _, _, M, _, _ = pr
    r = np.linalg.norm(pts, axis=1)
    n = pts / r[:, None]
    P = len(pts)
    g = np.zeros((P, 4, 4), dtype=DTYPE)
    g[:, 0, 0] = -N ** 2
    g[:, 0, 1] = g[:, 1, 0] = -beta * S
    g[:, 1:, 1:] = np.eye(3)[None] + (M - 1.0)[:, None, None] \
        * np.einsum('pi,pj->pij', n, n)
    return g


def T_at_g56(pts, pr, beta=BETA):
    """(T, g) at pts: Einstein tensor of the gate's
    metric, from the sympy-derived derivative tensors
    (g56_tensor) contracted by the gate's own assembly.
    DG[p, a, mu, nu] = d_a g_{mu nu} (a = 0 is t: zero)."""
    pts = np.asarray(pts, dtype=DTYPE)
    S, Sp, Spp, N, Np, Npp, M, Mp, Mpp = pr
    P = len(pts)
    g = metric_g56(pts, pr, beta)
    dg_s = GT.dg_np(pts[:, 0], pts[:, 1], pts[:, 2],
                    N, Np, Npp, M, Mp, Mpp, S, Sp, Spp, beta)
    ddg_s = GT.ddg_np(pts[:, 0], pts[:, 1], pts[:, 2],
                      N, Np, Npp, M, Mp, Mpp, S, Sp, Spp, beta)
    DG = np.zeros((P, 4, 4, 4), dtype=DTYPE)
    DG[:, 1:] = dg_s
    DDG = np.zeros((P, 4, 4, 4, 4), dtype=DTYPE)
    DDG[:, 1:, 1:] = ddg_s
    ginv = np.linalg.inv(g)
    # T1[p, d, b, c] = DG_b g_dc + DG_c g_db - DG_d g_bc
    T1 = (np.einsum('pbdc->pdbc', DG)
          + np.einsum('pcdb->pdbc', DG)
          - np.einsum('pdbc->pdbc', DG))
    Gam = 0.5 * np.einsum('pad,pdbc->pabc', ginv, T1)
    dginv = -np.einsum('pam,pemn,pnb->peab', ginv, DG, ginv)
    DT1 = (np.einsum('pebdc->pedbc', DDG)
           + np.einsum('pecdb->pedbc', DDG)
           - np.einsum('pedbc->pedbc', DDG))
    dGam = 0.5 * (np.einsum('pead,pdbc->peabc', dginv, T1)
                  + np.einsum('pad,pedbc->peabc', ginv, DT1))
    Ric = (np.einsum('paabd->pbd', dGam)
           - np.einsum('pdaba->pbd', dGam)
           + np.einsum('paae,pebd->pbd', Gam, Gam)
           - np.einsum('pade,peba->pbd', Gam, Gam))
    Rs = np.einsum('pab,pab->p', ginv, Ric)
    G = Ric - 0.5 * Rs[:, None, None] * g
    return G / EIGHT_PI, g


def eulerian_that_g56(g, T):
    """The gate's own ADM Eulerian orthonormal frame:
    e_0 = (1/alpha, -beta^i/alpha); spatial triad from
    the eigendecomposition of gamma."""
    gamma = g[:, 1:, 1:]
    beta_cov = g[:, 0, 1:]
    gamma_inv = np.linalg.inv(gamma)
    beta_up = np.einsum('pij,pj->pi', gamma_inv, beta_cov)
    alpha2 = -g[:, 0, 0] + np.einsum('pi,pi->p', beta_cov,
                                     beta_up)
    alpha = np.sqrt(np.maximum(alpha2, 1e-300))
    lam, V = np.linalg.eigh(gamma)
    P = len(g)
    E = np.zeros((P, 4, 4), dtype=DTYPE)
    E[:, 0, 0] = 1.0 / alpha
    E[:, 1:, 0] = -beta_up / alpha[:, None]
    for i in range(3):
        E[:, 1:, i + 1] = V[:, :, i] / np.sqrt(lam[:, i])[:, None]
    That = np.einsum('pma,pnb,pmn->pab', E, E, T)
    return 0.5 * (That + np.swapaxes(That, -1, -2))


# ------------------------------------------------ margins
def sampled_margins_g56(That):
    """The registered SAMPLER-M sampled fallback for
    non-Type-I points (162 Fibonacci dirs; velocities
    linspace(0, 0.95, 6)), independently coded from the
    definition."""
    That = np.asarray(That, dtype=DTYPE)
    flat = That.reshape(-1, 4, 4)
    Np = flat.shape[0]
    dirs = fib_dirs(162)
    T00 = flat[:, 0, 0]; T0i = flat[:, 0, 1:]
    Tij = flat[:, 1:, 1:]
    tr = np.trace(Tij, axis1=1, axis2=2)
    quad = np.einsum('njk,ij,ik->ni', Tij, dirs, dirs)
    nec_min = (T00[:, None] + 2.0 * (T0i @ dirs.T)
               + quad).min(axis=1)
    wec_min = np.full(Np, np.inf); sec_min = np.full(Np, np.inf)
    dec_min = np.full(Np, np.inf)
    Mm = flat.copy(); Mm[:, 0, :] *= -1.0
    for v in np.linspace(0.0, 0.95, 6):
        gam = 1.0 / np.sqrt(1.0 - v * v)
        base = (T00[:, None] + 2.0 * v * (T0i @ dirs.T)
                + v * v * quad)
        wec_vals = gam ** 2 * base
        wec_min = np.minimum(wec_min, wec_vals.min(axis=1))
        trT = -T00 + tr
        sec_vals = wec_vals - 0.5 * trT[:, None] * gam ** 2 \
            * (v * v - 1.0)
        sec_min = np.minimum(sec_min, sec_vals.min(axis=1))
        V = np.zeros((Np, 162, 4), dtype=DTYPE)
        V[:, :, 0] = gam
        V[:, :, 1:] = gam * v * dirs[None, :, :]
        Ups = -np.einsum('nab,nib->nia', Mm, V)
        q = Ups[:, :, 0] ** 2 - np.sum(Ups[:, :, 1:] ** 2, axis=2)
        nrm = 1.0 + np.sum(Ups ** 2, axis=2)
        val = np.where(Ups[:, :, 0] > 0, q / nrm,
                       -np.abs(q) / nrm - 1.0)
        dec_min = np.minimum(dec_min, val.min(axis=1))
    return {'nec': nec_min, 'wec': wec_min, 'sec': sec_min,
            'dec': dec_min}


def margins_g56(That):
    """The gate's Hawking-Ellis margins: mixed-tensor
    eigenvalues at Type-I points; the sampled fallback
    fills non-Type-I points (flagged)."""
    That = np.asarray(That, dtype=DTYPE)
    shp = That.shape[:-2]
    flat = That.reshape(-1, 4, 4)
    Np = flat.shape[0]
    M = flat.copy()
    M[:, 0, :] *= -1.0
    evals, evecs = np.linalg.eig(M)
    scale = np.maximum(np.max(np.abs(evals.real), axis=1),
                       1e-300)
    real_ok = np.max(np.abs(evals.imag), axis=1) < 1e-8 * scale
    ev2 = np.abs(evecs) ** 2
    norms = -ev2[:, 0, :] + ev2[:, 1, :] + ev2[:, 2, :] \
        + ev2[:, 3, :]
    cand = norms < -1e-6
    typeI = real_ok & (cand.sum(axis=1) == 1)
    k_idx = np.argmax(cand, axis=1)
    ar = np.arange(Np)
    rho = np.where(typeI, -evals[ar, k_idx].real, np.nan)
    mask = np.ones((Np, 4), dtype=bool)
    mask[ar, k_idx] = False
    ps_all = evals.real[mask].reshape(Np, 3)
    ps = np.where(typeI[:, None], ps_all, np.nan)
    with np.errstate(invalid='ignore'):
        nec = np.where(typeI, np.min(rho[:, None] + ps, axis=1),
                       np.nan)
        wec = np.where(typeI, np.minimum(
            rho, np.min(rho[:, None] + ps, axis=1)), np.nan)
        sec = np.where(typeI, np.minimum(
            np.min(rho[:, None] + ps, axis=1),
            rho + np.sum(ps, axis=1)), np.nan)
        dec = np.where(typeI, np.minimum(
            rho, rho - np.max(np.abs(ps), axis=1)), np.nan)
    filled = np.zeros(Np, dtype=bool)
    if np.any(~typeI):
        sub = sampled_margins_g56(flat[~typeI])
        idx = np.where(~typeI)[0]
        nec[idx] = sub['nec']; wec[idx] = sub['wec']
        sec[idx] = sub['sec']; dec[idx] = sub['dec']
        filled[idx] = True
    return {'rho_eig': rho.reshape(shp),
            'p': ps.reshape(shp + (3,)),
            'typeI': typeI.reshape(shp),
            'sampled_filled': filled.reshape(shp),
            'nec': nec.reshape(shp), 'wec': wec.reshape(shp),
            'sec': sec.reshape(shp), 'dec': dec.reshape(shp),
            'rho_euler': That[..., 0, 0]}


