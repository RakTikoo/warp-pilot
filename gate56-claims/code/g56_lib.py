def worst_null_exact(That1):
    """The gate's EXACT worst-null at one point:
    min over unit spatial n of k^T That k, k = (1, n),
    solved by the secular equation. q(n) = c + 2 f.n +
    n^T A n; the global minimum on |n| = 1 is at
    (A - mu I) n = -f with mu <= lambda_min(A) and
    ||n(mu)|| = 1 (||n(mu)||^2 is monotone increasing
    in mu on (-inf, lambda_min)). Returns the value,
    the direction, and the KKT certificate."""
    That1 = np.asarray(That1, dtype=DTYPE)
    c = float(That1[0, 0])
    f = That1[0, 1:].copy()
    A = 0.5 * (That1[1:, 1:] + That1[1:, 1:].T)
    lam, V = np.linalg.eigh(A)
    lam_min = float(lam[0])
    fh = V.T @ f
    fn = float(np.linalg.norm(f))
    out = {'lam_min_A': lam_min, 'hard_case': False}
    if fn < 1e-290:
        out.update(value=c + lam_min, n=V[:, 0].copy(), mu=lam_min,
                   cert_resid=0.0, cert_norm=0.0)
        return out
    scale = max(1.0, abs(lam_min))

    def phi(mu):
        return float(np.sum((fh / (lam - mu)) ** 2) - 1.0)

    lo = lam_min - (fn + scale)
    assert phi(lo) < 0.0
    hi = lam_min - 1e-13 * scale
    if phi(hi) <= 0.0:
        # hard case: f (near-)orthogonal to the lowest
        # eigenvector and ||n(lam_min)|| <= 1; the minimum
        # is attained at mu = lam_min with a component
        # along v_min. Solve on the orthogonal complement
        # and complete the norm along v_min.
        out['hard_case'] = True
        mu = lam_min
        n = -V[:, 1:] @ (fh[1:] / (lam[1:] - mu))
        rem = 1.0 - float(n @ n)
        if rem < 0.0:
            rem = 0.0
        n = n + np.sqrt(rem) * V[:, 0]
        val = c + 2.0 * float(f @ n) + float(n @ A @ n)
        out.update(value=val, n=n, mu=mu,
                   cert_resid=float(np.linalg.norm(
                       (A - mu * np.eye(3)) @ n + f)),
                   cert_norm=abs(float(np.linalg.norm(n)) - 1.0))
        return out
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if phi(mid) > 0.0:
            hi = mid
        else:
            lo = mid
        if hi - lo < 1e-15 * scale:
            break
    mu = 0.5 * (lo + hi)
    # Newton refinement on phi (phi is steep near the
    # root: a 1e-15 bracket in mu can leave ||n|| off by
    # ~1e-9, which inflates q at the unnormalised n).
    for _ in range(50):
        d = lam - mu
        ph = float(np.sum((fh / d) ** 2) - 1.0)
        if abs(ph) < 1e-15:
            break
        dph = 2.0 * float(np.sum(fh ** 2 / d ** 3))
        mu = mu - ph / dph
    n = -V @ (fh / (lam - mu))
    val_sec = c + 2.0 * float(f @ n) + float(n @ A @ n)
    # the deciding value is q at the renormalised
    # (feasible) direction
    nn = n / np.linalg.norm(n)
    val = c + 2.0 * float(f @ nn) + float(nn @ A @ nn)
    out.update(value=val, value_secular=val_sec, n=nn,
               mu=float(mu),
               cert_resid=float(np.linalg.norm(
                   (A - mu * np.eye(3)) @ n + f)),
               cert_norm=abs(float(np.linalg.norm(n)) - 1.0),
               cert_psd_min_eig=lam_min - float(mu))
    return out


def _q_of_n(That1, n):
    k = np.concatenate([[1.0], n])
    return float(k @ That1 @ k)


def worst_null_scan_polish(That1):
    """The registered corroboration: fib(642) scan +
    Nelder-Mead polish (maxiter 400, xatol 1e-10,
    fatol 1e-14) over (theta, phi)."""
    That1 = np.asarray(That1, dtype=DTYPE)
    qs = That1[0, 0] + 2.0 * (DIRS642 @ That1[0, 1:]) \
        + np.einsum('ni,ij,nj->n', DIRS642, That1[1:, 1:],
                    DIRS642)
    i0 = int(np.argmin(qs))
    scan = float(qs[i0])
    n0 = DIRS642[i0]
    th0 = float(np.arccos(np.clip(n0[2], -1.0, 1.0)))
    ph0 = float(np.arctan2(n0[1], n0[0]))

    def obj(x):
        th, ph = x
        n = np.array([np.sin(th) * np.cos(ph),
                      np.sin(th) * np.sin(ph), np.cos(th)])
        return _q_of_n(That1, n)

    res = minimize(obj, np.array([th0, ph0]),
                   method='Nelder-Mead',
                   options={'maxiter': 400, 'xatol': 1e-10,
                            'fatol': 1e-14})
    th, ph = res.x
    n = np.array([np.sin(th) * np.cos(ph),
                  np.sin(th) * np.sin(ph), np.cos(th)])
    return {'scan': scan, 'polish': float(res.fun),
            'n_polish': n}


# ------------------------------------------------ point and SET reads
def point_read_g56(cfg, pt, beta=BETA):
    """Full point read: profiles, That, margins,
    exact worst-null (+ scan/polish corroboration)."""
    pt = np.asarray(pt, dtype=DTYPE).reshape(1, 3)
    pr = profiles_g56(cfg, pt)
    T, g = T_at_g56(pt, pr, beta)
    That = eulerian_that_g56(g, T)
    m = margins_g56(That)
    wn = worst_null_exact(That[0])
    wsp = worst_null_scan_polish(That[0])
    r = float(np.linalg.norm(pt[0]))
    loc = {k: float(v[0]) for k, v in zip(
        ('S', 'Sp', 'Spp', 'N', 'Np', 'Npp', 'M', 'Mp', 'Mpp'),
        pr)}
    return {'pt': pt[0], 'r': r, 'That': That[0],
            'typeI': bool(m['typeI'][0]),
            'nec': float(m['nec'][0]), 'wec': float(m['wec'][0]),
            'dec': float(m['dec'][0]), 'sec': float(m['sec'][0]),
            'rho_eig': float(m['rho_eig'][0]),
            'rho_euler': float(m['rho_euler'][0]),
            'worst_null': wn, 'worst_null_scan_polish': wsp,
            'local': loc}


def set_read_g56(cfg, beta=BETA):
    """SET-244 read (41 radial midpoint nodes x 162
    Fibonacci dirs) on the gate's machinery."""
    rec = {k: [] for k in ('typeI', 'nec', 'wec', 'dec',
                           'sec', 'rho')}
    pts_all = []
    for rr in R_NODES:
        pts = DIRS162 * rr
        pr = profiles_g56(cfg, pts)
        T, g = T_at_g56(pts, pr, beta)
        That = eulerian_that_g56(g, T)
        m = margins_g56(That)
        rec['typeI'].append(m['typeI']); rec['nec'].append(m['nec'])
        rec['wec'].append(m['wec']); rec['dec'].append(m['dec'])
        rec['sec'].append(m['sec']); rec['rho'].append(That[:, 0, 0])
        pts_all.append(pts)
    R = {k: np.concatenate(v) for k, v in rec.items()}
    pts_all = np.concatenate(pts_all)
    radii = np.linalg.norm(pts_all, axis=1)
    i_nec = int(np.argmin(R['nec']))
    i_dec = int(np.argmin(R['dec']))
    tI = R['typeI']
    out = {
        'joint': float(min(R['nec'].min(), R['dec'].min())),
        'nec_min': float(R['nec'].min()),
        'dec_min': float(R['dec'].min()),
        'wec_min': float(R['wec'].min()),
        'sec_min': float(R['sec'].min()),
        'rho_min': float(R['rho'].min()),
        'nec_argmin_r': float(radii[i_nec]),
        'dec_argmin_r': float(radii[i_dec]),
        'nec_argmin_pt': pts_all[i_nec],
        'dec_argmin_pt': pts_all[i_dec],
        'typeI_fraction': float(np.mean(tI)),
        'typeI_nec_min': float(R['nec'][tI].min())
        if np.any(tI) else None,
        '_R': R, '_pts': pts_all,
    }
    return out


def adversary_polish_g56(cfg, setrec, beta=BETA):
    """The registered adversary polish on gate machinery:
    Nelder-Mead (maxiter 300, xatol 1e-4, fatol 1e-7)
    in (r, theta, phi) from the read's 5 lowest Type-I
    SET points; objective = point NEC if Type-I else
    NEC + 1. Result: the minimum over Type-I polished
    endpoints."""
    R, pts = setrec['_R'], setrec['_pts']
    tI = R['typeI']
    idx = np.where(tI)[0]
    order = idx[np.argsort(R['nec'][idx])[:5]]
    starts = pts[order]

    def raw(pt):
        pr = point_read_g56(cfg, pt, beta)
        return pr

    def obj(x):
        r, th, ph = x
        pt = r * np.array([np.sin(th) * np.cos(ph),
                           np.sin(th) * np.sin(ph), np.cos(th)])
        pr = raw(pt)
        return pr['nec'] if pr['typeI'] else pr['nec'] + 1.0

    best = None
    for s in starts:
        r0 = float(np.linalg.norm(s))
        th0 = float(np.arccos(np.clip(s[2] / r0, -1.0, 1.0)))
        ph0 = float(np.arctan2(s[1], s[0]))
        res = minimize(obj, np.array([r0, th0, ph0]),
                       method='Nelder-Mead',
                       options={'maxiter': 300, 'xatol': 1e-4,
                                'fatol': 1e-7})
        r, th, ph = res.x
        pt = r * np.array([np.sin(th) * np.cos(ph),
                           np.sin(th) * np.sin(ph), np.cos(th)])
        pr = raw(pt)
        if pr['typeI'] and (best is None
                            or pr['nec'] < best['value']):
            best = {'value': pr['nec'], 'r': float(r),
                    'pt': pt, 'typeI': True,
                    'source': 'polished'}
    return best


def peak_g56(vS, K_S, beta=BETA):
    """Peak |beta * S| of a shape vector: the registered
    FINE_R read, a 20,001-point dense scan, and a
    200,001-point check scan."""
    spl = _spline(int(K_S), vS)
    out = {}
    for name, rr in (('fine401', FINE_R),
                     ('dense20001', np.linspace(10.0, 20.0, 20001)),
                     ('check200001', np.linspace(10.0, 20.0, 200001))):
        S = spl.eval_all(rr)[0]
        pk = np.abs(beta * S)
        i = int(np.argmax(pk))
        out[name] = {'peak': float(pk[i]), 'radius': float(rr[i])}
    return out
